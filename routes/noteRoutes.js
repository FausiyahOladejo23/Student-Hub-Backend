const router = require('express').Router();
const { body, param } = require('express-validator');
const c = require('../controllers/noteController');
const validate = require('../middleware/validate');
const idRule = param('id').isMongoId().withMessage('Invalid note ID.');
const fields = [body('title').optional().trim().isLength({ min: 1, max: 160 }), body('content').optional().isString().isLength({ max: 10000 }), body('color').optional().isIn(['purple', 'blue', 'yellow', 'green', 'pink']), body('isPinned').optional().isBoolean()];
router.get('/', c.list);
router.post('/', [body('title').trim().isLength({ min: 1, max: 160 }), body('content').optional().isString().isLength({ max: 10000 }), body('color').optional().isIn(['purple', 'blue', 'yellow', 'green', 'pink']), body('isPinned').optional().isBoolean()], validate, c.create);
router.patch('/:id', idRule, ...fields, validate, c.update);
router.delete('/:id', idRule, validate, c.remove);
module.exports = router;
